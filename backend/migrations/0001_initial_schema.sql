-- 0001: базовая схема, восстановленная по SQL-запросам backend/server
-- (auth.repository, tracks.repository, sync.repository, top-chart.repository)
-- и dist/modules/guest. Все CREATE написаны с IF NOT EXISTS, поэтому на уже
-- существующей базе миграция ничего не ломает: недостающие таблицы
-- создаются, существующие остаются как есть.

CREATE TABLE IF NOT EXISTS users (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username         text        NOT NULL,
  email            text        NOT NULL,
  password_hash    text,                                  -- NULL у гостевых аккаунтов
  role             text        NOT NULL DEFAULT 'user'
                   CHECK (role IN ('user', 'admin', 'moderator')),
  guest_session_id text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tracks (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     integer     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  title       text        NOT NULL,
  artist      text,
  album       text,
  duration    integer,                                    -- секунды
  file_path   text        NOT NULL,                       -- путь внутри STORAGE_ROOT
  file_format text        NOT NULL,                       -- mp3, m4a, ... или 'metadata'
  file_size   bigint      NOT NULL DEFAULT 0,
  notes       text,
  is_public   boolean     NOT NULL DEFAULT false,
  play_count  integer     NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS playlists (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       integer     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  name          text        NOT NULL,
  description   text,
  playlist_type text        NOT NULL DEFAULT 'sync',
  nfc_uid       text,
  is_public     boolean     NOT NULL DEFAULT false,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- Первичный ключ (playlist_id, track_id) нужен для
-- ON CONFLICT (playlist_id, track_id) в sync.repository
CREATE TABLE IF NOT EXISTS playlist_tracks (
  playlist_id integer NOT NULL REFERENCES playlists (id) ON DELETE CASCADE,
  track_id    integer NOT NULL REFERENCES tracks (id) ON DELETE CASCADE,
  position    integer NOT NULL DEFAULT 0,
  PRIMARY KEY (playlist_id, track_id)
);

-- Общий каталог для гостей и топ-чартов, без владельца
CREATE TABLE IF NOT EXISTS guest_tracks (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       text        NOT NULL,
  artist      text,
  file_path   text        NOT NULL,
  file_format text        NOT NULL,
  duration    integer     NOT NULL DEFAULT 0,
  file_size   bigint      NOT NULL DEFAULT 0,
  is_active   boolean     NOT NULL DEFAULT true,
  play_count  integer     NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now()
);
